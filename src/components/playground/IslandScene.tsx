// ?island=full or ?island=lite picks one by hand.
function islandUrl() {
  const full = "/playground/island.glb", lite = "/playground/island-lite.glb";
  if (typeof window === "undefined") return full;
  const pick = new URLSearchParams(window.location.search).get("island");
  if (pick === "full" || pick === "lite") return pick === "lite" ? lite : full;
  const memory = (navigator as Navigator & { deviceMemory?: number }).deviceMemory ?? 8;
  const phone = window.matchMedia("(pointer: coarse)").matches && Math.min(screen.width, screen.height) < 820;
  return phone || memory <= 2 || (navigator.hardwareConcurrency ?? 8) <= 2 ? lite : full;
}
