// Turns src/content/community-words.json (the single source of every word the
// Community page can show) into a SQL migration that refreshes the database's
// copy in private.decisions and private.words.
//
//   node scripts/community-words-sql.mjs            -> writes supabase/migrations/<timestamp>_community_words.sql
//   node scripts/community-words-sql.mjs --stdout   -> prints the SQL instead
//
// Then apply the new file (Supabase MCP apply_migration, the SQL Editor, or `supabase db push`).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const words = JSON.parse(readFileSync(join(root, "src/content/community-words.json"), "utf8"));

const ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function check(list, items) {
  const seen = new Set();
  for (const { id } of items) {
    if (!ID.test(id)) throw new Error(`${list}: id "${id}" must be lowercase letters, digits and dashes`);
    if (seen.has(id)) throw new Error(`${list}: duplicate id "${id}"`);
    seen.add(id);
  }
}

const decisionRows = [];
const wordRows = [];

words.decisions.forEach((d, i) => {
  if (d.step !== i + 1) throw new Error(`decision "${d.key}" should be step ${i + 1}`);
  if (d.options.length < 4) throw new Error(`decision "${d.key}" needs at least 4 options (each round shows 4)`);
  check(d.key, d.options);
  decisionRows.push(`  (${d.step}, ${q(d.key)})`);
  d.options.forEach((o, p) => wordRows.push(`  (${q(d.key)}, ${q(o.id)}, ${p + 1})`));
});
if (words.decisions.length !== 8) throw new Error("a poster has exactly 8 decisions");

for (const list of ["adjective", "noun", "colour"]) {
  const items = words.names[list];
  if (!items?.length) throw new Error(`names.${list} is empty`);
  check(list, items);
  items.forEach((o, p) => wordRows.push(`  (${q(list)}, ${q(o.id)}, ${p + 1})`));
}

const sql = `-- Generated by scripts/community-words-sql.mjs from src/content/community-words.json.
-- Do not edit by hand: change the JSON and run the script again.
-- Replaces the database's copy of the word lists. Ids already stored on posters,
-- rounds and profiles are kept as they are.

delete from private.decisions;
insert into private.decisions (step, key) values
${decisionRows.join(",\n")};

delete from private.words;
insert into private.words (list, id, position) values
${wordRows.join(",\n")};
`;

if (process.argv.includes("--stdout")) {
  process.stdout.write(sql);
} else {
  const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
  const file = join(root, "supabase/migrations", `${stamp}_community_words.sql`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, sql);
  console.log(`Wrote ${file}`);
}
